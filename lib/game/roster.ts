export function getCharacterById(
  id: string,
  roster: CharacterDefinition[] = STARTER_CHARACTERS
): CharacterDefinition | undefined {
  return roster.find((c) => c.id === id);
}

export function getSquadCharacters(
  ids: string[],
  roster: CharacterDefinition[] = STARTER_CHARACTERS
): CharacterDefinition[] {
  return ids
    .map((id) => getCharacterById(id, roster))
    .filter((c): c is CharacterDefinition => Boolean(c));
}

export function getComplementaryEnemySquad(
  playerSquadIds: string[],
  roster: CharacterDefinition[] = STARTER_CHARACTERS
): CharacterDefinition[] {
  const playerSet = new Set(playerSquadIds);
  const remaining = roster.filter((c) => !playerSet.has(c.id));
  if (remaining.length >= 5) {
    return remaining.slice(0, 5);
  }
  const starterFallback = STARTER_CHARACTERS.filter((c) => !playerSet.has(c.id));
  if (starterFallback.length >= 5) {
    return starterFallback.slice(0, 5);
  }
  return getSquadCharacters(DEFAULT_ENEMY_SQUAD_IDS, STARTER_CHARACTERS);
}
