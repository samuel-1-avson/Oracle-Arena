import { computeAbilityPowerBudget } from './balance';
import {
  AbilityDefinition,
  CharacterDefinition,
  CONTENT_SCHEMA_VERSION,
  RULESET_VERSION,
} from './types';

type StarterCharacterInput = Omit<
  CharacterDefinition,
  | 'upgradePoints'
  | 'abilityCreationPoints'
  | 'evolutionStage'
  | 'statUpgrades'
  | 'learnedAbilities'
  | 'upgradeHistory'
>;

function withProgressionDefaults(raw: StarterCharacterInput): CharacterDefinition {
  const learnedAbilities: AbilityDefinition[] = [
    ...raw.specialAbilities,
    ...(raw.ultimateAbility ? [raw.ultimateAbility] : []),
  ];
  return {
    ...raw,
    upgradePoints: 0,
    abilityCreationPoints: 0,
    evolutionStage: 0,
    statUpgrades: {
      maxHp: 0,
      attack: 0,
      defense: 0,
      speed: 0,
      healingPower: 0,
    },
    learnedAbilities,
    upgradeHistory: [],
  };
}

function makeAbility(
  partial: Omit<AbilityDefinition, 'powerBudgetCost' | 'rulesetVersion' | 'prerequisites'> & {
    minLevel?: number;
  }
): AbilityDefinition {
  const { minLevel = 1, ...rest } = partial;
  const draft: AbilityDefinition = {
    ...rest,
    prerequisites: { minLevel },
    rulesetVersion: RULESET_VERSION,
    powerBudgetCost: 0,
  };
  draft.powerBudgetCost = computeAbilityPowerBudget(draft);
  return draft;
}

